"""Frozen bank loading; stamps refused, not coerced."""
from __future__ import annotations

import json
from pathlib import Path

from ..core.scenario import Scenario, from_json
from .generate import GENERATOR_VERSION

REPO_ROOT = Path(__file__).resolve().parents[3]


def load_bank(name: str = "v1") -> list[Scenario]:
    payload = json.loads((REPO_ROOT / "banks" / f"{name}.json").read_text("utf-8"))
    if payload["generator_version"] != GENERATOR_VERSION:
        raise ValueError(
            f"bank {name} was generated by {payload['generator_version']}, "
            f"current is {GENERATOR_VERSION}: refused, not coerced")
    return [from_json(json.dumps(s)) for s in payload["scenarios"]]
